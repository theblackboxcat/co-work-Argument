"""
surfaces.py — surface symbol systems.

Every surface encodes the SAME problem. The invariant that makes the
comparison meaningful:

    5 tokens per fact, 4 for the query header, 1 for the answer.

So sequence length, hence compute per example, is identical across all
surfaces. Without this, "no surface effect" is vacuous — it could just mean
one surface is cheaper. Six surfaces:

  zh    Chinese natural language
  en    English natural language
  lisp  symbolic list notation
  math  mathematical notation
  code  Python-like source
  alien an artificial language: same grammar, no human word semantics
        (3-syllable nonce strings). This is the *placebo* arm — if the
        theory is right, it behaves like the others.

Relation and entity labels differ per surface, but the RELATIONAL STRUCTURE
the sequence encodes is identical. The alien surface is generated by a fixed
seed so it is reproducible and equally consistent across conditions.
"""

import random
from typing import Dict, List

N_TOK_PER_FACT = 5
N_TOK_QUERY = 4
N_TOK_ANSWER = 1

SENSORY_ZH = ["含", "先", "动", "移", "近", "指", "向", "属", "覆", "随"]
SENSORY_EN = ["inside", "before", "acts", "moves", "near", "points",
              "faces", "belongs", "covers", "follows"]
SENSORY_LISP = ["in", "pre", "act", "mov", "adj", "pnt",
                "fcs", "bel", "cov", "fol"]
SENSORY_MATH = ["∈", "<", "→", "↦", "≈", "⇒", "⊃", "∈*", "⊇", "↝"]
SENSORY_CODE = ["in_", "pre_", "act_", "mov_", "adj_", "pnt_",
               "fcs_", "bel_", "cov_", "fol_"]

# entity token pools per surface (18 each)
ENT_ZH = list("甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉")
ENT_EN = [f"e{i}" for i in range(18)]
ENT_LISP = [f"v{i}" for i in range(18)]
ENT_MATH = [f"x_{i}" for i in range(18)]
ENT_CODE = [f"n{i}" for i in range(18)]


def _alien_lex(n_rel, n_ent, seed=20240):
    rng = random.Random(seed)
    cons = ["k", "z", "t", "m", "s", "p", "r", "d"]
    vow = ["a", "e", "i", "o", "u"]

    def word(n=3):
        return "".join([rng.choice(cons), rng.choice(vow), rng.choice(cons)])

    rels, seen = [], set()
    while len(rels) < n_rel:
        w = word()
        if w not in seen:
            seen.add(w)
            rels.append(w)
    ents, seen = [], set()
    while len(ents) < n_ent:
        w = word()
        if w not in seen:
            seen.add(w)
            ents.append(w)
    return rels, ents


SURFACES = ["zh", "en", "lisp", "math", "code", "alien"]

# --- extension so any n_rel up to 24 is covered, deterministically ----------
# Labels beyond the hand-written core are generated, not semantic; they exist
# only so the vocabulary can grow without changing token-per-fact.
_EXT = {
    "zh":  [f"关{i}" for i in range(24)],
    "en":  [f"rel{i}" for i in range(24)],
    "lisp": [f"r{i}" for i in range(24)],
    "math": [f"ρ{i}" for i in range(24)],
    "code": [f"r{i}_" for i in range(24)],
}


def _labels(name, n):
    core = {"zh": SENSORY_ZH, "en": SENSORY_EN, "lisp": SENSORY_LISP,
            "math": SENSORY_MATH, "code": SENSORY_CODE}[name]
    out = list(core[:n])
    i = 0
    while len(out) < n:
        cand = _EXT[name][i]
        if cand not in out:
            out.append(cand)
        i += 1
    return out


class Surface:
    def __init__(self, name: str, n_rel: int, n_ent: int = 18):
        self.name = name
        self.n_rel = n_rel
        self.n_ent = n_ent
        if name in ("zh", "en", "lisp", "math", "code"):
            self.rel = _labels(name, n_rel)
            self.ent = ENT_ZH[:n_ent] if name == "zh" else (
                ENT_EN[:n_ent] if name == "en" else (
                ENT_LISP[:n_ent] if name == "lisp" else (
                ENT_MATH[:n_ent] if name == "math" else ENT_CODE[:n_ent])))
        elif name == "alien":
            self.rel, self.ent = _alien_lex(n_rel, n_ent)
        else:
            raise ValueError(name)

    # ---------------------------------------------------------------- facts
    # INVARIANT: exactly N_TOK_PER_FACT tokens in every surface. This is what
    # makes "no surface effect" non-vacuous: sequence length, hence compute
    # per example, is identical across arms.
    def fact(self, a: int, r: int, b: int) -> List[str]:
        A, R, B = self.ent[a], self.rel[r], self.ent[b]
        if self.name == "zh":
            # 甲 含 乙 。 -> pad to 5 tokens so every surface matches
            return [A, R, B, "。", "，"]
        if self.name == "en":
            return [A, "is", R, B, "."]
        if self.name == "lisp":
            return ["(", R, A, B, ")"]
        if self.name == "math":
            return [A, R, B, ";", "~"]
        if self.name == "code":
            return [A, R, B, ")", ";"]
        return [A, R, B, "|", "~"]

    # ---------------------------------------------------------------- query
    # exactly N_TOK_QUERY + n_rel_in_query tokens; here depth<=3 -> we encode
    # the relation sequence, so query length is 2 + depth. We keep the
    # *fact* length invariant which is what sets compute per example for a
    # fixed problem size; query length is likewise identical across surfaces.
    def query(self, start: int, seq: List[int]) -> List[str]:
        A = self.ent[start]
        S = [self.rel[r] for r in seq]
        if self.name == "zh":
            return ["问", A, "则", *S]
        if self.name == "en":
            return ["q", A, "then", *S]
        if self.name == "lisp":
            return ["(", "q", A, *S]
        if self.name == "math":
            return ["Q", A, "->", *S]
        if self.name == "code":
            return ["q", A, ")", *S]
        return ["Q", A, ">", *S]

    def answer(self, a: int) -> List[str]:
        return [self.ent[a]]

    # ---------------------------------------------------------------- render
    def render(self, p) -> Dict:
        facts = []
        for (a, r, b) in p.facts:
            facts.append(self.fact(a, r, b))
        toks = [t for f in facts for t in f]
        toks += self.query(p.start, p.seq)
        tgt = self.answer(p.answer)
        return {"tokens": toks, "target": tgt,
                "n_tokens": len(toks), "n_facts": len(facts)}


class PermutedSurface(Surface):
    """Semantic-null control arm.

    Encodes exactly the same relational structure, but the relation LABELS are
    randomly permuted with respect to which type-transition they realise, so
    the surface no longer carries human sensory meaning for the relation it
    denotes. Two uses:

      mode='rel'   relation labels shuffled (entity labels untouched)
      mode='ent'   entity labels shuffled (relation labels untouched)

    This is the control that makes an H1 result non-vacuous. If real-language
    surfaces and these null surfaces have the SAME emergence threshold, then a
    flat threshold across languages really is a statement about structure
    rather than about all languages happening to be equally hard.
    """

    def __init__(self, name: str, n_rel: int, n_ent: int = 18,
                 mode: str = "rel", seed: int = 777):
        super().__init__(name, n_rel, n_ent)
        rng = random.Random(seed + n_rel * 13 + (0 if mode == "rel" else 1))
        if mode == "rel":
            shuffled = list(self.rel)
            rng.shuffle(shuffled)
            self.rel = shuffled
        else:
            shuffled = list(self.ent)
            rng.shuffle(shuffled)
            self.ent = shuffled
        self.mode = mode


